#!/usr/bin/env python3
"""Maintain the continuity registers from the briefs on disk.

  registers.py rebuild            rebuild registers/do_not_reuse_register.md from every brief
  registers.py append <brief.md>  append one edition's links to the register
  registers.py window [--now ISO] compute the monitoring window for the next edition
  registers.py priors [--n 3]     print the paths of the N most recent editions
  registers.py watchouts          print the open Watch Outs from the latest edition

The register is append-only in spirit: `rebuild` regenerates it from the
briefs folder, which is itself append-only.
"""
import argparse
import datetime as dt
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from brief_format_check import parse  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BRIEFS = os.path.join(ROOT, "briefs")
REG = os.path.join(ROOT, "registers", "do_not_reuse_register.md")
LINK_RE = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def editions():
    paths = sorted(glob.glob(os.path.join(BRIEFS, "*", "brief.md")))
    out = []
    for p in paths:
        parsed, problems = parse(p)
        if parsed is None:
            continue
        out.append((os.path.basename(os.path.dirname(p)), p, parsed))
    return out


def entry(folder, parsed):
    fm = parsed["front_matter"]
    lines = [f"## {fm.get('date', folder)} ({fm.get('weekday', '')}, {fm.get('source', '')})", ""]
    for sec, body in parsed["sections"].items():
        for l in body:
            for m in LINK_RE.finditer(l):
                story = LINK_RE.sub("", l[2:] if l.startswith("- ") else l).strip()
                story = re.split(r"(?<=[.!?])\s", story)[0][:120]
                lines.append(f"- {sec} | {m.group(1)} | {m.group(2)} | {story}")
    lines.append("")
    return "\n".join(lines)


def rebuild():
    eds = editions()
    head = ["# Do-not-reuse register", "",
            "Every link cited in every edition, newest first. A URL here must not be cited",
            "again as a new story; a follow-up refers back to the earlier edition instead.",
            "Regenerated by `scripts/registers.py rebuild`; briefs/ is the source of truth.", ""]
    body = [entry(f, p) for f, _, p in reversed(eds)]
    open(REG, "w", encoding="utf-8").write("\n".join(head + body))
    print(f"register rebuilt from {len(eds)} editions")


def append(path):
    parsed, problems = parse(path)
    if parsed is None:
        sys.exit("brief does not parse")
    folder = os.path.basename(os.path.dirname(os.path.abspath(path)))
    existing = open(REG, encoding="utf-8").read() if os.path.exists(REG) else "# Do-not-reuse register\n\n"
    marker = f"## {parsed['front_matter'].get('date')}"
    if marker in existing and folder in existing:
        print("edition already in register")
        return
    # insert after the header block (first blank line after the intro)
    parts = existing.split("\n## ", 1)
    new = parts[0].rstrip() + "\n\n" + entry(folder, parsed) + ("\n## " + parts[1] if len(parts) > 1 else "")
    open(REG, "w", encoding="utf-8").write(new)
    print(f"appended {folder}")


def window(now_iso=None):
    """Window start = the previous edition's window_end if recorded, else its
    sent_at, else 04:00 UTC of the previous business day. Window end = now."""
    now = dt.datetime.fromisoformat(now_iso.replace("Z", "+00:00")) if now_iso else dt.datetime.now(dt.timezone.utc)
    eds = editions()
    start = None
    label = "fallback"
    if eds:
        fm = eds[-1][2]["front_matter"]
        for key in ("window_end", "sent_at"):
            v = fm.get(key)
            if v:
                try:
                    start = dt.datetime.fromisoformat(v.replace("Z", "+00:00"))
                    label = f"previous edition {fm.get('date')} {key}"
                    break
                except ValueError:
                    pass
    if start is None or (now - start) > dt.timedelta(days=4):
        d = now.date() - dt.timedelta(days=1)
        while d.weekday() >= 5:
            d -= dt.timedelta(days=1)
        start = dt.datetime.combine(d, dt.time(2, 45), tzinfo=dt.timezone.utc)
        label = "fallback: 06:45 GST on the previous business day"
    gst = dt.timezone(dt.timedelta(hours=4))
    out = {
        "window_start_utc": start.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "window_end_utc": now.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "window_start_gst": start.astimezone(gst).strftime("%Y-%m-%d %H:%M"),
        "window_end_gst": now.astimezone(gst).strftime("%Y-%m-%d %H:%M"),
        "basis": label,
        "spans_weekend": any((start + dt.timedelta(days=i)).weekday() >= 5 for i in range(int((now - start).days) + 1)),
        "hours": round((now - start).total_seconds() / 3600, 1),
    }
    print(json.dumps(out, indent=1))


def priors(n):
    for f, p, _ in editions()[-n:]:
        print(p)


def watchouts():
    eds = editions()
    if not eds:
        return
    f, p, parsed = eds[-1]
    print(f"# Watch Outs carried from {f}")
    for l in parsed["sections"].get("Watch Outs", []):
        if l.strip():
            print(l)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("rebuild")
    ap_a = sub.add_parser("append"); ap_a.add_argument("brief")
    ap_w = sub.add_parser("window"); ap_w.add_argument("--now")
    ap_p = sub.add_parser("priors"); ap_p.add_argument("--n", type=int, default=3)
    sub.add_parser("watchouts")
    a = ap.parse_args()
    {"rebuild": lambda: rebuild(), "append": lambda: append(a.brief), "window": lambda: window(a.now),
     "priors": lambda: priors(a.n), "watchouts": watchouts}[a.cmd]()
