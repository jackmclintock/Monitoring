#!/usr/bin/env python3
"""Maintain the continuity registers from the briefs on disk.

  registers.py rebuild            rebuild registers/do_not_reuse_register.md from every brief
  registers.py append <brief.md>  append one edition's links to the register
  registers.py window [--now ISO] [--planner plan.json] [--extra] compute the monitoring window (24 h to 06:45 GST by default; --extra: since the latest edition)
  registers.py priors [--n 3]     print the paths of the N most recent editions
  registers.py watchouts          print the open Watch Outs from the latest edition

The register is append-only in spirit: `rebuild` regenerates it from the
briefs folder, which is itself append-only.
"""
import argparse
import datetime as dt
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from brief_format_check import parse  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
BRIEFS = os.path.join(ROOT, "briefs")
REG = os.path.join(ROOT, "registers", "do_not_reuse_register.md")
LINK_RE = re.compile(r"\[([^\]]+)\]\((https?://[^)\s]+)\)")


def editions():
    paths = sorted(glob.glob(os.path.join(BRIEFS, "*", "brief.md")))
    out = []
    for p in paths:
        parsed, problems = parse(p)
        if parsed is None:
            continue
        out.append((os.path.basename(os.path.dirname(p)), p, parsed))
    return out


def entry(folder, parsed):
    fm = parsed["front_matter"]
    lines = [f"## {fm.get('date', folder)} ({fm.get('weekday', '')}, {fm.get('source', '')})", ""]
    for sec, body in parsed["sections"].items():
        for l in body:
            for m in LINK_RE.finditer(l):
                story = LINK_RE.sub("", l[2:] if l.startswith("- ") else l).strip()
                story = re.split(r"(?<=[.!?])\s", story)[0][:120]
                lines.append(f"- {sec} | {m.group(1)} | {m.group(2)} | {story}")
    lines.append("")
    return "\n".join(lines)


def rebuild():
    eds = editions()
    head = ["# Do-not-reuse register", "",
            "Every link cited in every edition, newest first. A URL here must not be cited",
            "again as a new story; a follow-up refers back to the earlier edition instead.",
            "Regenerated by `scripts/registers.py rebuild`; briefs/ is the source of truth.", ""]
    body = [entry(f, p) for f, _, p in reversed(eds)]
    open(REG, "w", encoding="utf-8").write("\n".join(head + body))
    print(f"register rebuilt from {len(eds)} editions")


def append(path):
    parsed, problems = parse(path)
    if parsed is None:
        sys.exit("brief does not parse")
    folder = os.path.basename(os.path.dirname(os.path.abspath(path)))
    existing = open(REG, encoding="utf-8").read() if os.path.exists(REG) else "# Do-not-reuse register\n\n"
    marker = f"## {parsed['front_matter'].get('date')}"
    if marker in existing and folder in existing:
        print("edition already in register")
        return
    # insert after the header block (first blank line after the intro)
    parts = existing.split("\n## ", 1)
    new = parts[0].rstrip() + "\n\n" + entry(folder, parsed) + ("\n## " + parts[1] if len(parts) > 1 else "")
    open(REG, "w", encoding="utf-8").write(new)
    print(f"appended {folder}")


def latest_edition_end(briefs_dir=None):
    """UTC end of the most recent edition on disk (window_end, else sent_at)."""
    briefs_dir = briefs_dir or os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "briefs")
    best = None
    for name in sorted(os.listdir(briefs_dir)) if os.path.isdir(briefs_dir) else []:
        path = os.path.join(briefs_dir, name, "brief.md")
        if not os.path.exists(path):
            continue
        head = open(path, encoding="utf-8").read(2000)
        m = re.search(r"^window_end:\s*(\S+)", head, re.M) or re.search(r"^sent_at:\s*(\S+)", head, re.M)
        if not m:
            continue
        try:
            d = dt.datetime.fromisoformat(m.group(1).replace("Z", "+00:00"))
            d = d if d.tzinfo else d.replace(tzinfo=dt.timezone.utc)
        except Exception:
            continue
        if best is None or d > best[0]:
            best = (d, name)
    return best


def window(now_iso=None, planner_json=None, default_time="06:45", extra=False):
    """Monitoring window for the run happening at `now`.

    Default rule: a fixed 24-hour window ending at the standard run time
    (06:45 GST) on the day of the run, starting at the same time the day
    before. The window is anchored to the clock, not to when the previous
    edition happened to be sent, so a late or early run covers the same
    24 hours. Weekend and holiday gaps are NOT merged automatically: a
    Monday run covers Sunday 06:45 to Monday 06:45 unless the dashboard
    planner says otherwise (the team may plan a Friday-to-Monday recap
    there).

    Planner rule: when a planner entry (from the dashboard's settings
    document, passed as a JSON file of {"reports": [...]}) has a run_at
    within 90 minutes before `now`, its window_start and window_end are
    used instead. Entries carry GST or ISO timestamps.

    Extra rule (`--extra`, the dashboard's "Run an extra edition now"
    button): the window runs from the end of the latest edition on disk
    to now, so a mid-day extra edition covers only what the morning one
    did not, and the edition folder is dated with the hour and minute.
    """
    now = dt.datetime.fromisoformat(now_iso.replace("Z", "+00:00")) if now_iso else dt.datetime.now(dt.timezone.utc)
    gst = dt.timezone(dt.timedelta(hours=4))
    now_g = now.astimezone(gst)
    label = f"default: 24 hours to {default_time} GST"
    hh, mm = (int(x) for x in default_time.split(":"))
    end = now_g.replace(hour=hh, minute=mm, second=0, microsecond=0)
    if end > now_g + dt.timedelta(minutes=90):
        end = end - dt.timedelta(days=1)
    start = end - dt.timedelta(days=1)
    chosen = None
    if extra:
        last = latest_edition_end()
        if last and last[0] < now:
            start, end = last[0], now
            label = f"extra edition: since the end of edition {last[1]}"
        else:
            end = now
            start = now - dt.timedelta(days=1)
            label = "extra edition: 24 hours to now (no earlier edition found)"
    if not extra and planner_json and os.path.exists(planner_json):
        try:
            plan = json.load(open(planner_json, encoding="utf-8"))
            for r in plan.get("reports", []):
                try:
                    run_at = dt.datetime.fromisoformat(str(r.get("run_at")).replace("Z", "+00:00"))
                    if run_at.tzinfo is None:
                        run_at = run_at.replace(tzinfo=gst)
                except Exception:
                    continue
                if dt.timedelta(0) <= (now - run_at) <= dt.timedelta(minutes=90) or dt.timedelta(0) <= (run_at - now) <= dt.timedelta(minutes=5):
                    chosen = r
                    break
        except Exception:
            chosen = None
    if chosen:
        def parse(v):
            d = dt.datetime.fromisoformat(str(v).replace("Z", "+00:00"))
            return d if d.tzinfo else d.replace(tzinfo=gst)
        try:
            start, end = parse(chosen["window_start"]), parse(chosen["window_end"])
            label = f"planner entry {chosen.get('id', '')}: {chosen.get('label', '')}".strip()
        except Exception:
            pass
    start_u, end_u = start.astimezone(dt.timezone.utc), end.astimezone(dt.timezone.utc)
    out = {
        "window_start_utc": start_u.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "window_end_utc": end_u.strftime("%Y-%m-%dT%H:%M:%SZ"),
        "window_start_gst": start.astimezone(gst).strftime("%Y-%m-%d %H:%M"),
        "window_end_gst": end.astimezone(gst).strftime("%Y-%m-%d %H:%M"),
        "basis": label,
        "planner_entry": chosen,
        "spans_weekend": any((start_u + dt.timedelta(days=i)).astimezone(gst).weekday() >= 5 for i in range(int((end_u - start_u).days) + 1)),
        "hours": round((end_u - start_u).total_seconds() / 3600, 1),
        "edition_folder": now_g.strftime("%Y-%m-%d-%H%M") if (extra or chosen) else now_g.strftime("%Y-%m-%d"),
    }
    print(json.dumps(out, indent=1, default=str))


def priors(n):
    for f, p, _ in editions()[-n:]:
        print(p)


def watchouts():
    eds = editions()
    if not eds:
        return
    f, p, parsed = eds[-1]
    print(f"# Watch Outs carried from {f}")
    for l in parsed["sections"].get("Watch Outs", []):
        if l.strip():
            print(l)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("rebuild")
    ap_a = sub.add_parser("append"); ap_a.add_argument("brief")
    ap_w = sub.add_parser("window"); ap_w.add_argument("--now"); ap_w.add_argument("--planner", help="JSON file with the dashboard planner entries"); ap_w.add_argument("--time", default="06:45", help="standard run time, GST"); ap_w.add_argument("--extra", action="store_true", help="extra edition: window from the end of the latest edition to now")
    ap_p = sub.add_parser("priors"); ap_p.add_argument("--n", type=int, default=3)
    sub.add_parser("watchouts")
    a = ap.parse_args()
    {"rebuild": lambda: rebuild(), "append": lambda: append(a.brief), "window": lambda: window(a.now, a.planner, a.time, a.extra),
     "priors": lambda: priors(a.n), "watchouts": watchouts}[a.cmd]()
